local M = {}

local item_nodes = {
  const_item = true,
  enum_item = true,
  function_item = true,
  mod_item = true,
  static_item = true,
  struct_item = true,
  trait_item = true,
  type_item = true,
  union_item = true,
}

local function cargo_dir(bufnr)
  local file = vim.api.nvim_buf_get_name(bufnr)
  local start = file ~= "" and vim.fs.dirname(file) or vim.fn.getcwd()
  local manifest = vim.fs.find("Cargo.toml", { path = start, upward = true })[1]
  return manifest and vim.fs.dirname(manifest) or nil
end

local function current_item(bufnr)
  local ok, node = pcall(vim.treesitter.get_node, { bufnr = bufnr })
  if not ok then
    return nil
  end

  while node do
    if item_nodes[node:type()] then
      local name = node:field("name")[1]
      if name then
        return vim.treesitter.get_node_text(name, bufnr)
      end
    end
    node = node:parent()
  end
end

local function show_output(lines, title, focus)
  vim.cmd("botright new")
  local buf = vim.api.nvim_get_current_buf()
  vim.api.nvim_buf_set_name(buf, title)
  vim.bo[buf].buftype = "nofile"
  vim.bo[buf].bufhidden = "wipe"
  vim.bo[buf].swapfile = false
  vim.bo[buf].filetype = "rust"
  vim.api.nvim_buf_set_lines(buf, 0, -1, false, lines)
  vim.bo[buf].modifiable = false
  vim.bo[buf].readonly = true
  if focus then
    for line, text in ipairs(lines) do
      if text:find(focus, 1, true) then
        vim.api.nvim_win_set_cursor(0, { line, 0 })
        break
      end
    end
  end
end

function M.expand(selector, focus)
  if vim.fn.executable("cargo") == 0 or vim.fn.executable("cargo-expand") == 0 then
    vim.notify(
      "cargo-expand not found in PATH. Add pkgs.cargo-expand to your Nix devShell or global Nix configuration.",
      vim.log.levels.ERROR
    )
    return
  end

  local bufnr = vim.api.nvim_get_current_buf()
  local cwd = cargo_dir(bufnr)
  if not cwd then
    vim.notify("No Cargo.toml found for current buffer", vim.log.levels.ERROR)
    return
  end

  local command = { "cargo", "expand" }
  if selector and selector ~= "" then
    table.insert(command, selector)
  end

  vim.notify("Running " .. table.concat(command, " "), vim.log.levels.INFO)
  vim.system(command, { cwd = cwd, text = true }, function(result)
    vim.schedule(function()
      local output = result.code == 0 and result.stdout or result.stderr
      if not output or output == "" then
        output = "cargo expand exited with code " .. result.code
      end
      show_output(vim.split(output, "\n", { plain = true, trimempty = true }), "[cargo-expand]", focus)
      if result.code ~= 0 then
        vim.notify("cargo expand failed; error shown in scratch buffer", vim.log.levels.ERROR)
      end
    end)
  end)
end

function M.expand_item()
  local item = current_item(0)
  if item then
    -- Filtering with `cargo expand Item` omits sibling impl blocks generated by
    -- derives. Expand target and jump to item so generated impl remains visible.
    M.expand(nil, item)
    return
  end

  vim.ui.input({ prompt = "Rust item name to locate: " }, function(path)
    if path and path ~= "" then
      M.expand(nil, path:match("([^:]+)$"))
    end
  end)
end

function M.setup()
  if vim.fn.exists(":CargoExpand") == 0 then
    vim.api.nvim_create_user_command("CargoExpand", function(opts)
      M.expand(opts.args)
    end, { nargs = "?", desc = "Expand current Cargo target or item" })
    vim.api.nvim_create_user_command("CargoExpandItem", M.expand_item, {
      desc = "Expand Rust item under cursor",
    })
  end
end

return M
